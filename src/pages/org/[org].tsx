import { type NextPage } from 'next'
import NextError from 'next/error'

import { useState } from 'react'
import { UserCircleIcon } from '@heroicons/react/24/outline'

import { useRouter } from 'next/router'
import Head from 'next/head'
import Link from 'next/link'

import { trpc } from 'utils/trpc'
import Button from 'components/Button'
import NewProjectModal from 'components/NewProjectModal'

const Org: NextPage = () => {
    const router = useRouter()
    const slug = router.query.org as string

    const {
        data: org,
        error,
        status,
    } = trpc.org.getBySlug.useQuery(slug, { enabled: !!slug })
    const [openNewProjectModal, setOpenNewProjectModal] = useState(false)

    if (error) {
        return (
            <NextError
                title={error.message}
                statusCode={error.data?.httpStatus ?? 500}
            />
        )
    }
    if (status !== 'success') {
        return <div>Loading...</div>
    }

    const { name, id } = org

    const Projects = () => {
        const projects = org.projects || []
        return projects.length > 0 ? (
            <div>
                {projects.map(({ name, slug }) => (
                    <div className="mt-2 flex items-center" key={slug}>
                        <Link
                            className="text-lg hover:text-teal-200"
                            href={`/project/${slug}`}
                        >
                            <UserCircleIcon className="mr-2 inline-block h-8 w-8" />
                            {name}
                        </Link>
                    </div>
                ))}
            </div>
        ) : (
            <></>
        )
    }

    return (
        <>
            <Head>
                <title>{name}</title>
                {/* <meta name="description" content="Generated by create-t3-app" /> */}
                <link rel="icon" href="/favicon.ico" />
            </Head>
            <>
                <div className="relative flex min-h-screen flex-col">
                    <NewProjectModal
                        open={openNewProjectModal}
                        setOpen={setOpenNewProjectModal}
                        organizationId={id}
                    />
                    {/* 3 column wrapper */}
                    <div className="mx-auto w-full max-w-7xl flex-grow lg:flex xl:px-8">
                        {/* Left sidebar & main wrapper */}
                        <div className="min-w-0 flex-1  xl:flex">
                            <div className="border-b border-gray-200 xl:w-64 xl:flex-shrink-0 xl:border-b-0 xl:border-r xl:border-gray-200">
                                <div className="h-full py-6 pl-4 pr-6 sm:pl-6 lg:pl-8 xl:pl-0">
                                    {/* Start left column area */}
                                    <div className="relative h-full">
                                        <div className="flex flex-col">
                                            <div className="text-4xl font-bold">
                                                {name}
                                            </div>
                                            <div className="mt-4 mb-2 text-3xl font-bold">
                                                Avatars
                                            </div>
                                            <Projects />
                                            <Button
                                                text="Create Avatar"
                                                classNames="mt-4 text-center self-start"
                                                onClick={() => {
                                                    setOpenNewProjectModal(true)
                                                    console.log('create avatar')
                                                }}
                                            />
                                        </div>
                                    </div>
                                    {/* End left column area */}
                                </div>
                            </div>

                            <div className="lg:min-w-0 lg:flex-1">
                                <div className="h-full py-6 px-4 sm:px-6 lg:px-8">
                                    {/* Start main area*/}
                                    <div
                                        className="relative h-full"
                                        style={{ minHeight: '36rem' }}
                                    >
                                        <div className="absolute inset-0 ">
                                            <div className="text-4xl font-bold">
                                                Members
                                            </div>
                                        </div>
                                    </div>
                                    {/* End main area */}
                                </div>
                            </div>
                        </div>
                    </div>
                </div>
            </>
        </>
    )
}

export default Org
